/// The player spawns at the configured (0, 0), feet on the first air block
/// above the spawn column: the grass of `SPAWN_CHUNK[0][0]` is at Y 63.
const SPAWN: Vec3 = Vec3 {
    x: 0.0,
    y: 64.0,
    z: 0.0,
};

/// Adjacent columns never differ by more than one block, chunk border or not.
const MAX_STEP: i32 = 1;

// ---------------------------------------------------------------------------
// The two generation paths and the world they are explored with.
// ---------------------------------------------------------------------------

const VIEW_DISTANCE: i32 = 3;

struct GenerationPath {
    name: &'static str,
    spawn_chunk_radius: i32,
    max_chunk_generations_per_tick: usize,
}

/// The default path, with a budget small enough to spread the streamed
/// chunks over many ticks.
const OPTIMIZED: GenerationPath = GenerationPath {
    name: "optimized",
    spawn_chunk_radius: 1,
    max_chunk_generations_per_tick: 2,
};

/// No spawn area beyond the spawn chunk, no generation budget (0 = unlimited).
const REFERENCE: GenerationPath = GenerationPath {
    name: "reference",
    spawn_chunk_radius: 0,
    max_chunk_generations_per_tick: 0,
};

fn square(center: ChunkPos, radius: i32) -> HashSet<ChunkPos> {
    (-radius..=radius)
        .flat_map(|dx| {
            (-radius..=radius).map(move |dz| ChunkPos::new(center.x + dx, center.z + dz))
        })
        .collect()
}

fn client_pos(pos: VoidChunkPos) -> ChunkPos {
    ChunkPos::new(pos.x, pos.z)
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Event {
    Generated(VoidChunkPos),
    TickEnd,
}

type EventLog = Arc<Mutex<Vec<Event>>>;

/// `DefaultWorldGenerator`, recording every chunk it generates.
struct RecordingGenerator {
    inner: DefaultWorldGenerator,
    log: EventLog,
}

impl WorldGenerator for RecordingGenerator {
    fn generate_chunk(&self, pos: &VoidChunkPos) -> Chunk {
        self.log.lock().unwrap().push(Event::Generated(*pos));
        self.inner.generate_chunk(pos)
    }

    fn surface_height_at(&self, block_x: i32, block_z: i32) -> i32 {
        self.inner.surface_height_at(block_x, block_z)
    }
}

/// Chunks generated before the first tick ended (the spawn area), then per
/// tick.
fn generations_per_tick(log: &[Event]) -> (Vec<VoidChunkPos>, Vec<usize>) {
    let mut segments = log.split(|event| *event == Event::TickEnd);
    let startup = segments
        .next()
        .unwrap_or_default()
        .iter()
        .filter_map(|event| match event {
            Event::Generated(pos) => Some(*pos),
            Event::TickEnd => None,
        })
        .collect();
    (startup, segments.map(<[Event]>::len).collect())
}

/// Block states of one chunk as the client holds it, indexed
/// `(y - MIN_Y) * 256 + z * 16 + x`.
type ClientChunk = Vec<BlockState>;

fn index(x: i32, y: i32, z: i32) -> usize {
    ((y - MIN_Y) * 256 + z * 16 + x) as usize
}

fn snapshot(bot: &Bot, into: &mut BTreeMap<(i32, i32), ClientChunk>) {
    let chunks: Vec<(ChunkPos, ClientChunk)> = bot.view(|view| {
        view.chunks
            .keys()
            .map(|pos| {
                let mut blocks = vec![BlockState::AIR; index(0, MAX_Y + 1, 0)];
                for y in MIN_Y..=MAX_Y {
                    for z in 0..16 {
                        for x in 0..16 {
                            let block = BlockPos::new(pos.x * 16 + x, y, pos.z * 16 + z);
                            blocks[index(x, y, z)] = view
                                .block_at(block)
                                .expect("the chunk is held by the client");
                        }
                    }
                }
                (*pos, blocks)
            })
            .collect()
    });
    for (pos, blocks) in chunks {
        if let Some(earlier) = into.insert((pos.x, pos.z), blocks) {
            assert!(
                earlier == into[&(pos.x, pos.z)],
                "chunk {pos:?} changed between two snapshots of the same client"
            );
        }
    }
}

fn runs(chunk: &ClientChunk, x: i32, z: i32) -> Vec<(BlockKind, i32, i32)> {
    let mut runs: Vec<(BlockKind, i32, i32)> = Vec::new();
    for y in MIN_Y..=MAX_Y {
        let kind = BlockKind::from(chunk[index(x, y, z)]);
        match runs.last_mut() {
            Some((last, _, to)) if *last == kind => *to = y,
            _ => runs.push((kind, y, y)),
        }
    }
    runs
}

/// Checks every column of every chunk against the fixture rule and returns
/// the grass Y of every column, keyed by block `(x, z)`.
fn grass_heights(
    terrain: &BTreeMap<(i32, i32), ClientChunk>,
    path: &str,
) -> HashMap<(i32, i32), i32> {
    let mut heights = HashMap::new();
    for (&(chunk_x, chunk_z), chunk) in terrain {
        for z in 0..16 {
            for x in 0..16 {
                let (block_x, block_z) = (chunk_x * 16 + x, chunk_z * 16 + z);
                let runs = runs(chunk, x, z);
                let grass = runs
                    .iter()
                    .find(|(kind, _, _)| *kind == BlockKind::GrassBlock)
                    .map(|(_, y, _)| *y)
                    .unwrap_or_else(|| {
                        panic!("{path}: column ({block_x}, {block_z}) has no grass")
                    });
                assert_eq!(
                    runs,
                    column_rule(grass),
                    "{path}: column ({block_x}, {block_z}) breaks the column rule"
                );
                heights.insert((block_x, block_z), grass);
            }
        }
    }
    heights
}

/// Compares the client's terrain with the fixture.
fn assert_fixture(terrain: &BTreeMap<(i32, i32), ClientChunk>, path: &str) {
    let heights = grass_heights(terrain, path);

    let mut borders = 0;
    for (&(x, z), &grass_y) in &heights {
        for (nx, nz) in [(x + 1, z), (x, z + 1)] {
            let Some(&neighbour) = heights.get(&(nx, nz)) else {
                continue;
            };
            if (nx != x && nx.rem_euclid(16) == 0) || (nz != z && nz.rem_euclid(16) == 0) {
                borders += 1;
            }
            assert!(
                (grass_y - neighbour).abs() <= MAX_STEP,
                "{path}: the terrain jumps from Y {grass_y} at ({x}, {z}) to Y {neighbour} at ({nx}, {nz})"
            );
        }
    }
    assert!(borders > 0, "{path}: no chunk border was compared");

    let spawn_chunk: Vec<Vec<i32>> = (0..16)
        .map(|z| (0..16).map(|x| heights[&(x, z)]).collect())
        .collect();
    assert_eq!(
        spawn_chunk, SPAWN_CHUNK,
        "{path}: the spawn chunk is not the fixture"
    );
    for &(x, z, grass_y) in COLUMNS {
        assert_eq!(
            heights.get(&(x, z)),
            Some(&grass_y),
            "{path}: column ({x}, {z}) is not the fixture"
        );
    }
}

/// What a client saw of the world through one generation path.
struct Explored {
    terrain: BTreeMap<(i32, i32), ClientChunk>,
    startup: Vec<VoidChunkPos>,
    per_tick: Vec<usize>,
}

fn builder(path: &GenerationPath, log: &EventLog) -> TestServerBuilder {
    let generator_log = log.clone();
    let tick_log = log.clone();
    let spawn_chunk_radius = path.spawn_chunk_radius;
    let budget = path.max_chunk_generations_per_tick;
    TestServer::builder()
        .config(move |config| {
            config
                .view_distance(VIEW_DISTANCE)
                .spawn_chunk_radius(spawn_chunk_radius)
                .initial_chunk_radius(1)
                .max_chunk_generations_per_tick(budget)
                .world_generator(RecordingGenerator {
                    inner: DefaultWorldGenerator::default(),
                    log: generator_log,
                })
        })
        .plugin(move |app| {
            app.add_systems(Last, move || {
                tick_log.lock().unwrap().push(Event::TickEnd);
            });
        })
}

/// Server-side chunks that differ, byte for byte, from a chunk regenerated by
/// a fresh `DefaultWorldGenerator`.
async fn regenerated_mismatches(server: &TestServer) -> Vec<VoidChunkPos> {
    server
        .with_world(|world| {
            let biome_count = world.resource::<RegistryDataStore>().biome_count();
            let generator = DefaultWorldGenerator::default();
            let chunks: Vec<_> = world
                .resource::<ChunkIndex>()
                .0
                .clone()
                .into_iter()
                .collect();
            chunks
                .into_iter()
                .filter(|((dimension, pos), entity)| {
                    assert_eq!(*dimension, DimensionId::Overworld);
                    let held = world
                        .get::<ChunkData>(*entity)
                        .expect("indexed chunks have data");
                    let mut regenerated =
                        ChunkData::from_protocol_chunk(&generator.generate_chunk(pos));
                    regenerated.normalize_biomes(biome_count);
                    format!("{:?}", held.to_packet(pos.x, pos.z))
                        != format!("{:?}", regenerated.to_packet(pos.x, pos.z))
                })
                .map(|((_, pos), _)| pos)
                .collect()
        })
        .await
}

async fn indexed_chunks(server: &TestServer) -> HashSet<ChunkPos> {
    server
        .with_world(|world| {
            world
                .resource::<ChunkIndex>()
                .0
                .keys()
                .map(|(_, pos)| client_pos(*pos))
                .collect()
        })
        .await
}

/// Where the server placed the bot when it joined.
async fn spawn_teleport(bot: &Bot) -> Vec3 {
    bot.expect("the spawn teleport", |packet| match packet {
        ClientboundGamePacket::PlayerPosition(teleport) => Some(teleport.change.pos),
        _ => None,
    })
    .await
}

/// Starts a server on `path`, joins, crosses from chunk (0, 0) into chunk
/// (1, 0) and back, and returns every chunk the client received on the way.
async fn explore(path: &GenerationPath) -> Explored {
    let name = path.name;
    let log = EventLog::default();
    let server = builder(path, &log).start().await;

    let spawn_area = square(ChunkPos::new(0, 0), path.spawn_chunk_radius);
    assert_eq!(
        indexed_chunks(&server).await,
        spawn_area,
        "{name}: the world did not start with the spawn area"
    );

    let alice = server
        .join_with(
            "Alice",
            BotOptions {
                view_distance: VIEW_DISTANCE as u8,
            },
        )
        .await;
    assert_eq!(
        spawn_teleport(&alice).await,
        SPAWN,
        "{name}: spawn position"
    );
    let joined = square(ChunkPos::new(0, 0), VIEW_DISTANCE);
    alice
        .wait_until("the chunks around the spawn", |view| {
            view.chunks.keys().copied().collect::<HashSet<_>>() == joined
        })
        .await;
    let mut terrain = BTreeMap::new();
    snapshot(&alice, &mut terrain);

    alice.move_to(Vec3::new(8.5, 80.0, 0.5)).await;
    alice.move_to(Vec3::new(16.5, 80.0, 0.5)).await;
    let crossed = ChunkPos::new(1, 0);
    let moved = square(crossed, VIEW_DISTANCE);
    alice
        .wait_until("the chunks around chunk (1, 0)", |view| {
            view.chunk_center == Some(crossed)
                && view.chunks.keys().copied().collect::<HashSet<_>>() == moved
        })
        .await;
    alice.sync().await;
    snapshot(&alice, &mut terrain);

    // Walking back re-sends the chunks forgotten on the way out, from the
    // cache: the snapshot fails if they changed.
    alice.move_to(Vec3::new(8.5, 80.0, 0.5)).await;
    alice.move_to(Vec3::new(0.5, 80.0, 0.5)).await;
    alice
        .wait_until("the chunks around the spawn again", |view| {
            view.chunk_center == Some(ChunkPos::new(0, 0))
                && view.chunks.keys().copied().collect::<HashSet<_>>() == joined
        })
        .await;
    alice.sync().await;
    snapshot(&alice, &mut terrain);

    let generated: HashSet<ChunkPos> = joined.union(&moved).copied().collect();
    assert_eq!(
        terrain
            .keys()
            .map(|&(x, z)| ChunkPos::new(x, z))
            .collect::<HashSet<_>>(),
        generated,
        "{name}: the client did not receive the expected chunks"
    );
    assert_eq!(
        indexed_chunks(&server).await,
        generated,
        "{name}: the server holds other chunks than the ones streamed"
    );
    let mismatches = regenerated_mismatches(&server).await;
    assert!(
        mismatches.is_empty(),
        "{name}: {} server chunks differ from a regenerated chunk, among them {:?}",
        mismatches.len(),
        &mismatches[..mismatches.len().min(5)]
    );

    let log = log.lock().unwrap().clone();
    let mut times_generated: HashMap<VoidChunkPos, usize> = HashMap::new();
    for event in &log {
        if let Event::Generated(pos) = event {
            *times_generated.entry(*pos).or_default() += 1;
        }
    }
    let regenerated: Vec<_> = times_generated
        .iter()
        .filter(|(_, count)| **count > 1)
        .collect();
    assert!(
        regenerated.is_empty(),
        "{name}: chunks generated more than once instead of being served from the cache: {regenerated:?}"
    );
    let (startup, per_tick) = generations_per_tick(&log);

    alice.assert_healthy();
    server.stop().await;
    Explored {
        terrain,
        startup,
        per_tick,
    }
}

/// Compares every block the client holds with a chunk generated directly by
/// `DefaultWorldGenerator`.
fn assert_matches_the_generator(terrain: &BTreeMap<(i32, i32), ClientChunk>, path: &str) {
    let generator = DefaultWorldGenerator::default();
    for (&(chunk_x, chunk_z), chunk) in terrain {
        let pos = VoidChunkPos::new(chunk_x, chunk_z);
        let expected = ChunkData::from_protocol_chunk(&generator.generate_chunk(&pos));
        for y in MIN_Y..=MAX_Y {
            for z in 0..16 {
                for x in 0..16 {
                    let seen = u32::from(chunk[index(x, y, z)]) as i32;
                    let wanted = expected
                        .get_block(x as u8, y, z as u8)
                        .expect("y is inside the world");
                    assert_eq!(
                        seen,
                        wanted,
                        "{path}: block ({}, {y}, {}) of chunk {pos:?} differs from the generator",
                        chunk_x * 16 + x,
                        chunk_z * 16 + z
                    );
                }
            }
        }
    }
}

#[tokio::test]
async fn optimized_generation_matches_the_fixture_at_spawn_and_across_a_chunk_boundary() {
    let explored = explore(&OPTIMIZED).await;

    let spawn_area: HashSet<ChunkPos> = square(ChunkPos::new(0, 0), OPTIMIZED.spawn_chunk_radius);
    assert_eq!(
        explored
            .startup
            .iter()
            .map(|pos| client_pos(*pos))
            .collect::<HashSet<_>>(),
        spawn_area,
        "the spawn area was not generated at startup"
    );
    assert_eq!(
        explored.startup.len(),
        9,
        "a spawn-area chunk was generated twice"
    );

    let budget = OPTIMIZED.max_chunk_generations_per_tick;
    let busiest = explored.per_tick.iter().copied().max().unwrap_or(0);
    assert!(
        busiest <= budget,
        "a tick generated {busiest} chunks, over the budget of {budget}"
    );
    assert_eq!(busiest, budget, "the streaming never reached the budget");
    let streamed: usize = explored.per_tick.iter().sum();
    assert_eq!(streamed, 7 * 7 + 7 - 9, "chunks generated while streaming");

    assert_fixture(&explored.terrain, OPTIMIZED.name);
    assert_matches_the_generator(&explored.terrain, OPTIMIZED.name);
}

#[tokio::test]
async fn optimized_and_reference_paths_generate_identical_terrain() {
    let reference = explore(&REFERENCE).await;
    let optimized = explore(&OPTIMIZED).await;

    assert_eq!(reference.startup, vec![VoidChunkPos::new(0, 0)]);
    let busiest = reference.per_tick.iter().copied().max().unwrap_or(0);
    assert!(
        busiest > OPTIMIZED.max_chunk_generations_per_tick,
        "the reference path is throttled too ({busiest} chunks at most per tick)"
    );
    assert_fixture(&reference.terrain, REFERENCE.name);

    assert_eq!(
        reference.terrain.keys().collect::<Vec<_>>(),
        optimized.terrain.keys().collect::<Vec<_>>()
    );
    for (pos, chunk) in &reference.terrain {
        assert!(
            optimized.terrain[pos] == *chunk,
            "chunk {pos:?} differs between the reference and the optimized path"
        );
    }
}

/// A spawn area smaller than the join radius must not leave holes: the
/// chunks the join could not take from the spawn area are streamed even when
/// the view distance equals the join radius.
#[tokio::test]
async fn the_whole_view_arrives_when_the_spawn_area_is_smaller_than_the_join_radius() {
    let server = TestServer::builder()
        .config(|config| {
            config
                .view_distance(2)
                .spawn_chunk_radius(0)
                .initial_chunk_radius(2)
        })
        .start()
        .await;
    let alice = server.join("Alice").await;

    let view = square(ChunkPos::new(0, 0), 2);
    alice
        .wait_until("every chunk within the view distance", |client| {
            client.chunks.keys().copied().collect::<HashSet<_>>() == view
        })
        .await;
    assert_eq!(spawn_teleport(&alice).await, SPAWN, "spawn position");
    let ground = alice
        .view(|client| client.ground_below(BlockPos::new(0, 64, 0)))
        .expect("the spawn chunk is held");
    assert_eq!(ground, BlockPos::new(0, 63, 0));
    assert_eq!(
        alice.block_at(ground).map(BlockKind::from),
        Some(BlockKind::GrassBlock)
    );

    alice.assert_healthy();
    server.stop().await;
}
