//! VMC-ATP-027: optimized world generation produces the fixture terrain and
//! spawn area.
//!
//! The optimized path is the one the server runs by default: the spawn area is
//! generated once at startup (`spawn_chunk_radius`), each chunk is generated
//! at most once and then served from the `ChunkIndex` cache, and the chunks
//! streamed to a moving player are generated under a per-tick budget
//! (`max_chunk_generations_per_tick`). The reference path turns that off: no
//! spawn area beyond the spawn chunk and no budget.
//!
//! A client joins, checks its spawn and the terrain it receives against the
//! fixture below, crosses a chunk boundary and checks the newly streamed
//! chunks too. Every chunk is also compared, block by block on the client and
//! byte for byte on the server, with a chunk freshly regenerated by
//! `DefaultWorldGenerator`, and the optimized path must deliver exactly the
//! terrain of the reference path.

use std::collections::{BTreeMap, HashMap, HashSet};
use std::sync::{Arc, Mutex};

use bevy_app::Last;
use voidmc::{
    ChunkData, ChunkIndex, ChunkPos as VoidChunkPos, DefaultWorldGenerator, DimensionId,
    RegistryDataStore, WorldGenerator,
};
use voidmc_e2e::block::BlockState;
use voidmc_e2e::core::position::{BlockPos, ChunkPos, Vec3};
use voidmc_e2e::protocol::packets::game::ClientboundGamePacket;
use voidmc_e2e::registry::builtin::BlockKind;
use voidmc_e2e::{Bot, BotOptions, TestServer, TestServerBuilder};
use voidmc_protocol::clientbound::Chunk;

// ---------------------------------------------------------------------------
// The terrain fixture: the world `DefaultWorldGenerator::default()` must
// produce. Any change to the generator's output fails these scenarios.
// ---------------------------------------------------------------------------

const MIN_Y: i32 = -64;
const MAX_Y: i32 = 319;
/// Water fills every block above the terrain up to this Y.
const WATER_TOP: i32 = 62;

/// Every column, from the bottom up: stone from `MIN_Y`, three dirt, one
/// grass block at `grass_y`, water up to `WATER_TOP` if the grass is below
/// it, then air to the top of the world.
fn column_rule(grass_y: i32) -> Vec<(BlockKind, i32, i32)> {
    let mut runs = vec![
        (BlockKind::Stone, MIN_Y, grass_y - 4),
        (BlockKind::Dirt, grass_y - 3, grass_y - 1),
        (BlockKind::GrassBlock, grass_y, grass_y),
    ];
    let air_from = if grass_y < WATER_TOP {
        runs.push((BlockKind::Water, grass_y + 1, WATER_TOP));
        WATER_TOP + 1
    } else {
        grass_y + 1
    };
    runs.push((BlockKind::Air, air_from, MAX_Y));
    runs
}

